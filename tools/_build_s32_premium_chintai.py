def format_entry(slug: str, qa: list[tuple[str, str]]) -> str:
    lines = [f'    "{slug}": [']
    for q, a in qa:
        lines.append("        (")
        lines.append(f'            "{q}",')
        lines.append(f'            "{a}",')
        lines.append("        ),")
    lines.append("    ],")
    return "\n".join(lines)


